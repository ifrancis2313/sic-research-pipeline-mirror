"""Ticker/ISIN -> FIGI crosswalk, owned by whichever adapter needs it.

Backed by `crosswalk_cache.json`, meant to be generated by
`scripts/refresh_figi_crosswalk.py` via a real OpenFIGI (Bloomberg's free
symbology API) batch resolution against real source data -- not intended
as a hand-maintained placeholder dict. This public mirror's committed
cache holds synthetic sample values, since no real source data ships here.
Falls back to a tiny inline placeholder (with a loud warning) only if the
cache file is missing, e.g. before the refresh script has been run once, or
in an offline dev environment.

Swap `TICKER_TO_FIGI`/`ISIN_TO_FIGI` (or the adapter's `ticker_to_figi`
argument) for a different resolver later with no change to the adapter's
interface or anything downstream -- they're consumed as plain dicts.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path

logger = logging.getLogger(__name__)

_CACHE_PATH = Path(__file__).with_name("crosswalk_cache.json")

_PLACEHOLDER_TICKER_TO_FIGI: dict[str, str] = {
    "SPX": "PLACEHOLDER-FIGI-SPX",
}
_PLACEHOLDER_ISIN_TO_FIGI: dict[str, str] = {
    "US0000000101": "PLACEHOLDER-FIGI-A",  # example equity A
    "US0000000102": "PLACEHOLDER-FIGI-B",  # example equity B
}


def _load() -> tuple[dict[str, str], dict[str, str]]:
    if not _CACHE_PATH.exists():
        logger.warning(
            "%s not found -- falling back to placeholder FIGI values; "
            "run scripts/refresh_figi_crosswalk.py to generate a real cache",
            _CACHE_PATH,
        )
        return dict(_PLACEHOLDER_TICKER_TO_FIGI), dict(_PLACEHOLDER_ISIN_TO_FIGI)
    cache = json.loads(_CACHE_PATH.read_text())
    return cache["ticker_to_figi"], cache["isin_to_figi"]


TICKER_TO_FIGI, ISIN_TO_FIGI = _load()
